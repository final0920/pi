#!/usr/bin/env node
/**
 * Generate the TypeScript module for the built-in purge prompt.
 *
 * `packages/coding-agent/src/extensions/purge/prompt.md` is the editable source of
 * truth; the generated `prompt.ts` is what the extension imports. Embedding the text
 * keeps the prompt identical across source checkouts, npm installs, and standalone
 * binaries, so no asset-copy step can drop it.
 *
 * Usage:
 *   node scripts/embed-purge-prompt.mjs           # write prompt.ts
 *   node scripts/embed-purge-prompt.mjs --check   # fail if prompt.ts is stale
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(repoRoot, "packages/coding-agent/src/extensions/purge/prompt.md");
const outputPath = resolve(repoRoot, "packages/coding-agent/src/extensions/purge/prompt.ts");

const BANNER = `// Generated by scripts/embed-purge-prompt.mjs from ./prompt.md. Do not edit by hand.
// Run \`npm run embed:purge-prompt\` after changing prompt.md.
`;

/** Escape a prompt body for embedding in a template literal. */
function toTemplateLiteral(text) {
	return text.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
}

const prompt = readFileSync(sourcePath, "utf8");
if (!prompt.trim()) {
	throw new Error(`Prompt source is empty: ${relative(repoRoot, sourcePath)}`);
}

const generated = `${BANNER}
/** Built-in purge prompt. Injected verbatim as the \`purge\` system-prompt section. */
export const PURGE_PROMPT = \`${toTemplateLiteral(prompt)}\`;
`;

const check = process.argv.includes("--check");

if (check) {
	let current = "";
	try {
		current = readFileSync(outputPath, "utf8");
	} catch {
		console.error(`${relative(repoRoot, outputPath)} is missing. Run \`npm run embed:purge-prompt\`.`);
		process.exit(1);
	}
	if (current !== generated) {
		console.error(`${relative(repoRoot, outputPath)} is out of date with prompt.md.`);
		console.error("Run `npm run embed:purge-prompt` and commit the result.");
		process.exit(1);
	}
	console.log(`${relative(repoRoot, outputPath)} is up to date.`);
} else {
	writeFileSync(outputPath, generated, "utf8");
	console.log(`Wrote ${relative(repoRoot, outputPath)} (${prompt.length} chars from prompt.md).`);
}
